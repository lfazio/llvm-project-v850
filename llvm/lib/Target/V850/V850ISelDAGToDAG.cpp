class V850DAGToDAGISel : public SelectionDAGISel {
  const V850Subtarget *Subtarget = nullptr;

public:
  V850DAGToDAGISel() = delete;

  explicit V850DAGToDAGISel(V850TargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<V850Subtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *N) override;

// Include the pieces autogenerated from the target description.
#include "V850GenDAGISel.inc"
};

