#ifndef LLVM_LIB_TARGET_V850_V850SUBTARGET_H
#define LLVM_LIB_TARGET_V850_V850SUBTARGET_H

#include "V850FrameLowering.h"
#include "V850ISelLowering.h"
#include "V850InstrInfo.h"
#include "V850RegisterInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "V850GenSubtargetInfo.inc"

namespace llvm {

class StringRef;

class V850Subtarget : public V850GenSubtargetInfo {
  virtual void anchor();

  // Subtarget feature flags - set by ParseSubtargetFeatures
  bool HasV850E1 = false;
  bool HasV850E2 = false;
  bool HasV850E2M = false;
  bool HasV850FPU = false;
  bool HasV850E3 = false;
  bool HasRH850G3M = false;
  bool HasV850FPIPR = false;
  bool HasRH850G3MH = false;
  bool HasV850FXU = false;
  bool HasRH850G4MH = false;
  bool HasRH850G4MH2 = false;

  V850InstrInfo InstrInfo;
  V850TargetLowering TLInfo;
  V850FrameLowering FrameLowering;
  SelectionDAGTargetInfo TSInfo;

public:
  /// This constructor initializes the data members to match that
  /// of the specified triple.
  V850Subtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                const TargetMachine &TM);

  V850Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  /// ParseSubtargetFeatures - Parses features string setting specified
  /// subtarget options. Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const V850InstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const V850RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const V850TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  // Feature predicates
  bool hasV850E1() const { return HasV850E1; }
  bool hasV850E2() const { return HasV850E2; }
  bool hasV850E2M() const { return HasV850E2M; }
  bool hasV850FPU() const { return HasV850FPU; }
  bool hasV850E3() const { return HasV850E3; }
  bool hasRH850G3M() const { return HasRH850G3M; }
  bool hasV850FPIPR() const { return HasV850FPIPR; }
  bool hasRH850G3MH() const { return HasRH850G3MH; }
  bool hasV850FXU() const { return HasV850FXU; }
  bool hasRH850G4MH() const { return HasRH850G4MH; }
  bool hasRH850G4MH2() const { return HasRH850G4MH2; }

  // Post-RA scheduling support
  // Enable anti-dependency breaking for all registers to improve scheduling
  AntiDepBreakMode getAntiDepBreakMode() const override { return ANTIDEP_ALL; }

  // Specify GPR register class for critical path analysis during post-RA
  // scheduling
  void getCriticalPathRCs(RegClassVector &CriticalPathRCs) const override;
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_V850_V850SUBTARGET_H
